UNION ALL SELECT id,'PRACTICE','TRANSLATION' FROM cet_paper
UNION ALL SELECT id,'INTENSIVE','LONG_CONVERSATION' FROM cet_paper
UNION ALL SELECT id,'INTENSIVE','LISTENING_PASSAGE' FROM cet_paper
