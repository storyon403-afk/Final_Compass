CREATE TABLE cet_paper_section (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  paper_id BIGINT NOT NULL,
  mode ENUM('PRACTICE','INTENSIVE') NOT NULL,
  section VARCHAR(32) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_cet_paper_section_paper FOREIGN KEY (paper_id) REFERENCES cet_paper(id) ON DELETE CASCADE,
  UNIQUE KEY uk_cet_paper_section (paper_id,mode,section)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

